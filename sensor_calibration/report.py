"""Generate calibration metrics and plots from reference/ADC CSV data."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from .calibration import fit_linear_calibration, regression_metrics


def read_dataset(path: Path) -> list[dict[str, float | int]]:
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    required = {"reference_pressure_kpa", "raw_adc", "replicate"}
    if not rows or not required.issubset(rows[0]):
        raise ValueError(f"CSV must contain columns: {sorted(required)}")
    return [
        {
            "reference_pressure_kpa": float(row["reference_pressure_kpa"]),
            "raw_adc": float(row["raw_adc"]),
            "replicate": int(row["replicate"]),
        }
        for row in rows
    ]


def analyze_dataset(input_path: Path, output_dir: Path) -> dict[str, object]:
    rows = read_dataset(input_path)
    reference = np.array([row["reference_pressure_kpa"] for row in rows], dtype=float)
    raw_adc = np.array([row["raw_adc"] for row in rows], dtype=float)
    replicate = np.array([row["replicate"] for row in rows], dtype=int)

    # Hold out the last replicate at each reference pressure. This avoids
    # reporting only a training fit as if it were independent validation.
    train_mask = replicate < replicate.max()
    validation_mask = ~train_mask
    model = fit_linear_calibration(raw_adc[train_mask], reference[train_mask])
    predicted = model.predict(raw_adc)
    train_metrics = regression_metrics(reference[train_mask], predicted[train_mask])
    validation_metrics = regression_metrics(reference[validation_mask], predicted[validation_mask])

    output_dir.mkdir(parents=True, exist_ok=True)
    report = {
        "input": input_path.name,
        "data_source": "synthetic calibration data generated by this repository",
        "sample_count": len(rows),
        "calibration_sample_count": int(train_mask.sum()),
        "validation_sample_count": int(validation_mask.sum()),
        "model": "linear pressure-from-ADC least-squares fit",
        "equation": model.equation,
        "training_metrics": train_metrics,
        "validation_metrics": validation_metrics,
        "limitations": [
            "The dataset is synthetic and does not validate a physical optical-fiber sensor.",
            "The reference pressure is treated as ground truth for this software demonstration.",
            "ADC pin, photodetector circuit, optical coupling, and sampling rate require hardware verification.",
        ],
    }
    (output_dir / "calibration_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")

    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5), constrained_layout=True)
    axes[0].scatter(reference[train_mask], predicted[train_mask], label="calibration", alpha=0.8)
    axes[0].scatter(reference[validation_mask], predicted[validation_mask], label="validation", marker="x", s=70)
    lower = min(reference.min(), predicted.min())
    upper = max(reference.max(), predicted.max())
    axes[0].plot([lower, upper], [lower, upper], "--", color="black", label="ideal")
    axes[0].set(xlabel="reference pressure (kPa)", ylabel="estimated pressure (kPa)", title="Calibration fit")
    axes[0].grid(True, alpha=0.3)
    axes[0].legend()

    residuals = predicted - reference
    axes[1].axhline(0.0, color="black", linewidth=0.8)
    axes[1].scatter(reference[train_mask], residuals[train_mask], label="calibration", alpha=0.8)
    axes[1].scatter(reference[validation_mask], residuals[validation_mask], label="validation", marker="x", s=70)
    axes[1].set(xlabel="reference pressure (kPa)", ylabel="residual (kPa)", title="Calibration residuals")
    axes[1].grid(True, alpha=0.3)
    axes[1].legend()

    fig.suptitle("Optical-fiber pressure sensor calibration — synthetic data")
    fig.savefig(output_dir / "calibration_report.png", dpi=150)
    plt.close(fig)
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input_csv", type=Path)
    parser.add_argument("--output-dir", type=Path, default=Path("results"))
    args = parser.parse_args()
    print(json.dumps(analyze_dataset(args.input_csv, args.output_dir), indent=2))


if __name__ == "__main__":
    main()

